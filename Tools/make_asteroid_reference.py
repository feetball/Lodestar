"""Writes the JPL Horizons reference positions that the bundled-asteroid tests compare with (CatalogAsteroidReferenceData.kt/.swift).

For a few of the bundled asteroids it asks Horizons (https://ssd.jpl.nasa.gov/api/horizons.api) for the geocentric astrometric
J2000 right ascension and declination at days after the epoch of the MPC elements (2026-06-09, JD 2461200.5), then prints
both files. Usage: python3 -I Tools/make_asteroid_reference.py KOTLIN_FILE SWIFT_FILE
"""
import json
import sys
import urllib.parse
import urllib.request

EPOCH = 2461200.5
OFFSETS = [0.0, 30.0, 120.0, 131.0, 365.0, 731.0]
TARGETS = [("1", "(1) Ceres"), ("2", "(2) Pallas"), ("3", "(3) Juno"), ("4", "(4) Vesta"), ("7", "(7) Iris"),
           ("6", "(6) Hebe"), ("433", "(433) Eros")]
QUERIED = "2026-10-18"


def horizons(params):
    query = urllib.parse.urlencode(params, doseq=True)
    with urllib.request.urlopen("https://ssd.jpl.nasa.gov/api/horizons.api?" + query, timeout=180) as response:
        return json.loads(response.read().decode())["result"]


def observer(designation):
    params = dict(format="json", COMMAND=f"'{designation};'", OBJ_DATA="'NO'", MAKE_EPHEM="'YES'", EPHEM_TYPE="'OBSERVER'",
                  CENTER="'500@399'", TLIST_TYPE="'JD'", TIME_TYPE="'UT'", TLIST="'" + " ".join(repr(EPOCH + o) for o in OFFSETS) + "'",
                  QUANTITIES="'1'", ANG_FORMAT="'DEG'", CSV_FORMAT="'YES'", EXTRA_PREC="'YES'", TIME_DIGITS="'FRACSEC'")
    text = horizons(params)
    lines = text.splitlines()
    start = next(i for i, line in enumerate(lines) if line.startswith("$$SOE"))
    end = next(i for i, line in enumerate(lines) if line.startswith("$$EOE"))
    rows = []
    for line in lines[start + 1:end]:
        cells = [cell.strip() for cell in line.split(",")]
        rows.append((float(cells[-3]), float(cells[-2])))
    if len(rows) != len(OFFSETS):
        sys.exit(f"unexpected answer for {designation}:\n{text[:2000]}")
    return rows


def main():
    results = [(d, title, observer(d)) for d, title in TARGETS]
    kotlin = ['package net.kuecker.lodestar.kit.catalog', '', '/**',
              f' * Geocentric astrometric J2000 positions of bundled asteroids from JPL Horizons ({QUERIED}, https://ssd.jpl.nasa.gov/api/horizons.api,',
              " * EPHEM_TYPE=OBSERVER, CENTER=500@399, QUANTITIES=1, TLIST in UT), at days after JD 2461200.5, the epoch of the MPC elements.",
              ' * Generated by Tools/make_asteroid_reference.py; the numbers are Horizons\' own digits.', ' */',
              'internal object CatalogAsteroidReferenceData {',
              '    /** The Julian Day (TT) of the osculating epoch of the MPC elements, 2026 June 9. */',
              f'    const val epochJulianDay: Double = {EPOCH}', '',
              '    /** The days after the epoch of the rows of every asteroid. */',
              '    val offsetsDays: List<Double> = listOf(' + ", ".join(repr(o) for o in OFFSETS) + ')', '',
              '    /** One asteroid: its designation as in `SmallBody.designation`, its title and the (RA, Dec) in degrees per offset. */',
              '    class Reference(val designation: String, val title: String, val positions: List<Pair<Double, Double>>)', '',
              '    val references: List<Reference> = listOf']
    kotlin[-1] += '('
    swift = ['import Foundation', '', '/// Geocentric astrometric J2000 positions of bundled asteroids from JPL Horizons (' + QUERIED + ', https://ssd.jpl.nasa.gov/api/horizons.api,',
             '/// EPHEM_TYPE=OBSERVER, CENTER=500@399, QUANTITIES=1, TLIST in UT), at days after JD 2461200.5, the epoch of the MPC elements.',
             "/// Generated by Tools/make_asteroid_reference.py; the numbers are Horizons' own digits.",
             'enum CatalogAsteroidReferenceData {',
             '    /// The Julian Day (TT) of the osculating epoch of the MPC elements, 2026 June 9.',
             f'    static let epochJulianDay = {EPOCH}', '',
             '    /// The days after the epoch of the rows of every asteroid.',
             '    static let offsetsDays: [Double] = [' + ", ".join(repr(o) for o in OFFSETS) + ']', '',
             '    /// One asteroid: its designation as in `SmallBody.designation`, its title and the (RA, Dec) in degrees per offset.',
             '    struct Reference {', '        let designation: String', '        let title: String',
             '        let positions: [(rightAscension: Double, declination: Double)]', '    }', '',
             '    static let references: [Reference] = [']
    for designation, title, rows in results:
        kotlin.append(f'        Reference(\n            "{designation}", "{title}",\n            listOf(')
        for ra, dec in rows:
            kotlin.append(f'                Pair({ra!r}, {dec!r}),')
        kotlin.append('            ),\n        ),')
        swift.append(f'        Reference(designation: "{designation}", title: "{title}", positions: [')
        for ra, dec in rows:
            swift.append(f'            ({ra!r}, {dec!r}),')
        swift.append('        ]),')
    kotlin.append('    )')
    kotlin.append('}')
    swift.append('    ]')
    swift.append('}')
    open(sys.argv[1], "w").write("\n".join(kotlin) + "\n")
    open(sys.argv[2], "w").write("\n".join(swift) + "\n")


if __name__ == "__main__":
    main()
